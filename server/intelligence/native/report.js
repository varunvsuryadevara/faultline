// Native Report Intelligence Engine for FaultLine.
// Synthesizes a comprehensive, audit-ready forensic investigation report without external AI.
// Fully functional offline with zero API calls.

import { constructNativeTimeline } from './timeline.js';
import { detectNativeContradictions } from './contradiction.js';
import { detectNativeCorroborations } from './corroboration.js';
import { evaluateNativeRiskIndicators } from './risk.js';
import { evaluateInvestigationCompleteness } from './completeness.js';
import { evaluatePolicyCompliance } from './policy.js';
import { queryLegalIntelligence } from '../legal.js';

export function generateNativeInvestigationReport({ caseFile, scenario = null, jurisdiction = 'UK' }) {
  const exhibits = caseFile?.exhibits || [];
  const title = caseFile?.title || scenario?.title || 'Motor Incident Investigation Dossier';
  const incidentDate = caseFile?.incidentDate || new Date().toISOString().slice(0, 10);

  // 1. Run all native intelligence modules deterministically
  const timeline = constructNativeTimeline(exhibits);
  const contradictions = detectNativeContradictions(exhibits);
  const corroborations = detectNativeCorroborations(exhibits);
  const risk = evaluateNativeRiskIndicators(exhibits, caseFile?.context);
  const completeness = evaluateInvestigationCompleteness(exhibits, caseFile?.context);
  const policy = evaluatePolicyCompliance(exhibits);
  const legal = queryLegalIntelligence({ country: scenario?.country || jurisdiction, limit: 3 });

  // 2. Synthesize Recommended Disposition under Safeguards
  let recommendedDisposition = 'APPROVE';
  let dispositionRationale = '';

  if (contradictions.hasMaterialContradictions && risk.hasCriticalRisk) {
    recommendedDisposition = 'REJECT';
    dispositionRationale = `Grounds for REJECT: Physical forensic evidence and material contradictions confirm fabricated or pre-existing vehicle damage not consistent with the reported loss event.`;
  } else if (!completeness.isSufficientForDecision || contradictions.total > 0 || risk.total > 0) {
    recommendedDisposition = 'REVIEW';
    dispositionRationale = `Grounds for REVIEW: Case file has unresolved witness discrepancies or missing documentation (${completeness.missingRequired.join(', ') || 'further proof needed'}). Safeguards dictate keeping claim under review pending clarification.`;
  } else {
    recommendedDisposition = 'APPROVE';
    dispositionRationale = `Grounds for APPROVE: Consistent driver statements independently corroborated by physical damage geometry and telematics records with no material fraud indicators.`;
  }

  // 3. Assemble Structured Markdown Report
  let report = `# FaultLine Native Forensic Investigation Report\n\n`;
  report += `**Investigation Title:** ${title}\n`;
  report += `**Case ID / Scenario:** ${scenario?.id || caseFile?.scenarioId || 'CUSTOM-INVESTIGATION'}\n`;
  report += `**Date of Loss:** ${incidentDate}\n`;
  report += `**Jurisdiction:** ${scenario?.country || jurisdiction} (${legal.regulations[0]?.title || 'Standard Framework'})\n`;
  report += `**Generated By:** FaultLine Native Intelligence Engine (Offline Mode • 100% Deterministic)\n`;
  report += `**Report Timestamp:** ${new Date().toISOString()}\n\n`;
  report += `---\n\n`;

  // Section 1: Executive Disposition
  report += `## 1. EXECUTIVE DECISION RECOMMENDATION\n\n`;
  report += `### **RECOMMENDED DISPOSITION: \`${recommendedDisposition}\`**\n\n`;
  report += `**Forensic Assessment Rationale:**\n${dispositionRationale}\n\n`;
  report += `• **Overall Risk Assessment:** \`${risk.overallRisk}\`\n`;
  report += `• **Evidence Completeness:** ${completeness.completenessRatio} (${completeness.completenessPercentage}%)\n`;
  report += `• **Contradictions Identified:** ${contradictions.total} (${contradictions.materialCount} material)\n`;
  report += `• **Corroborations Identified:** ${corroborations.total} (${corroborations.independentCount} independent)\n\n`;
  report += `> [!NOTE]\n`;
  report += `> *Bad-Faith Litigation Guard: This recommendation is generated to assist authorized human claims handlers. Final disposition requires secondary adjuster sign-off under Two-Key Governance.* \n\n`;

  // Section 2: Evidence Manifest
  report += `## 2. EVIDENCE MANIFEST & PROVENANCE\n\n`;
  report += `The investigation dossier incorporates **${exhibits.length} formal exhibits**:\n\n`;
  exhibits.forEach((e, idx) => {
    report += `• **Exhibit ${e.label || `X${idx + 1}`}** (\`${e.kind || 'statement'}\`)\n`;
    report += `  - Summary Excerpt: *"${(e.text || '').slice(0, 120)}..."*\n`;
    report += `  - Attachments: ${(e.attachments || []).map((a) => a.name).join(', ') || 'Direct Text Input'}\n`;
  });
  report += `\n`;

  // Section 3: Reconstruction Timeline
  report += `## 3. FORENSIC INCIDENT TIMELINE\n\n`;
  if (timeline.events.length > 0) {
    timeline.events.forEach((ev) => {
      report += `• **[${ev.time || 'Time Unspecified'}] ${ev.eventType}** (\`${ev.classification}\`)\n`;
      report += `  - Source: ${ev.exhibitLabel} | Snippet: *"${ev.snippet}"*\n`;
      if (ev.speed) report += `  - Recorded Velocity: **${ev.speed}**\n`;
    });
  } else {
    report += `*Insufficient timestamp markers to reconstruct minute-by-minute timeline.*\n`;
  }
  if (timeline.hasTimestampConflicts) {
    report += `\n**⚠ Conflicting Timestamp Warnings:**\n`;
    timeline.conflictingTimestamps.forEach((tc) => {
      report += `• ${tc.description}\n`;
    });
  }
  report += `\n`;

  // Section 4: Contradiction Analysis
  report += `## 4. Contradiction & Cross-Examination Audit\n\n`;
  if (contradictions.total > 0) {
    contradictions.contradictions.forEach((c) => {
      report += `### Finding ${c.id}: ${c.type} (\`${c.severity}\`)\n`;
      report += `• **Discrepancy:** ${c.description}\n`;
      report += `• **Source A:** ${c.sourceA}\n`;
      report += `• **Source B:** ${c.sourceB}\n`;
      report += `• **Verification Status:** ${c.verificationStatus}\n`;
      report += `• **Investigative Limitation:** ${c.limitations}\n`;
      report += `• **Action:** ${c.recommendedNextStep}\n\n`;
    });
  } else {
    report += `*No direct factual or physical contradictions identified across current exhibits.*\n\n`;
  }

  // Section 5: Corroboration Findings
  report += `## 5. INDEPENDENT CORROBORATIONS\n\n`;
  if (corroborations.total > 0) {
    corroborations.corroborations.forEach((cb) => {
      report += `• **Corroborated Fact:** ${cb.fact}\n`;
      report += `  - Supporting Sources: ${cb.sources.join(', ')}\n`;
      report += `  - Independent Verification: ${cb.isIndependent ? 'YES' : 'NO (shared source citation)'}\n`;
      report += `  - Confidence: ${(cb.confidenceScore * 100).toFixed(0)}%\n\n`;
    });
  } else {
    report += `*No multi-source factual corroborations identified.*\n\n`;
  }

  // Section 6: Risk Indicators
  report += `## 6. EXPLAINABLE RISK INDICATORS\n\n`;
  if (risk.total > 0) {
    risk.indicators.forEach((ri) => {
      report += `• **[${ri.severity}] ${ri.title}** (\`${ri.id}\`)\n`;
      report += `  - Explanation: ${ri.explanation}\n`;
      report += `  - Triggering Rule: ${ri.triggeringRule}\n`;
      report += `  - Triggering Exhibits: ${ri.triggeringEvidence.join(', ')}\n`;
      report += `  - Limitation Note: ${ri.limitations}\n`;
      report += `  - Recommended Action: ${ri.recommendedAction}\n\n`;
    });
  } else {
    report += `*No fraud or staged collision risk indicators triggered by case rules.*\n\n`;
  }

  // Section 7: Investigation Completeness & Next Steps
  report += `## 7. INVESTIGATION COMPLETENESS & NEXT STEPS\n\n`;
  completeness.requirements.forEach((req) => {
    report += `[${req.status === 'PRESENT' ? '✔' : ' '}] **${req.item}** (\`${req.level}\` - \`${req.status}\`)\n`;
    report += `    ${req.rationale}\n`;
  });
  report += `\n**Mandatory Steps Before Settlement:**\n`;
  if (completeness.missingRequired.length > 0) {
    completeness.missingRequired.forEach((m) => {
      report += `• Request and inspect: **${m}**\n`;
    });
  } else {
    report += `• All mandatory investigation items are on file.\n`;
  }
  report += `\n`;

  // Section 8: Statutory Legal Context
  report += `## 8. STATUTORY LEGAL FRAMEWORK (${legal.country})\n\n`;
  legal.regulations.forEach((reg) => {
    report += `• **${reg.legalReference}:** *${reg.title}*\n`;
    report += `  - Statutory Requirement: ${reg.summary}\n`;
    report += `  - Claims Implication: ${reg.investigationImplications}\n`;
    report += `  - Verified Source: [${reg.sourceUrl}](${reg.sourceUrl})\n\n`;
  });

  return {
    markdown: report,
    recommendedDisposition,
    dispositionRationale,
    overallRisk: risk.overallRisk,
    completenessPercentage: completeness.completenessPercentage,
    contradictionsCount: contradictions.total,
    corroborationsCount: corroborations.total,
    metrics: {
      contradictionCount: contradictions.total,
      corroborationCount: corroborations.total,
      timelineEventsCount: timeline.totalEvents,
      completenessPercentage: completeness.completenessPercentage,
    },
    compliance: {
      badFaithGuardCompliant: true,
      safeguardAdhered: true,
    },
  };
}
